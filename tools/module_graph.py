"""Generate the engine's package import graph in `docs/architecture/modules.md`,
grouped by the containers of `docs/architecture/model.toml` whose code reaches
each package, and the import contracts in `pyproject.toml` that keep each
container's code imported by its own package alone. Check both, and check
each container's `runs` against the packages its `code` reaches.

    python3 tools/module_graph.py write   # rewrite the graph and the contracts
    python3 tools/module_graph.py check   # fail on a stale graph or contract
"""

import ast
import sys
import textwrap
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
DOCS = ROOT / "docs" / "architecture"
MODEL = DOCS / "model.toml"
PAGE = DOCS / "modules.md"
PYPROJECT = ROOT / "pyproject.toml"
BEGIN = "<!-- generated by `just module-graph`, never edited -->"
END = "<!-- end of the generated graph -->"
RULES_BEGIN = "# generated from model.toml by `just module-graph`, never edited"
RULES_END = "# end of the generated contracts"
# every package may import these, so an arrow into one is not drawn; the first
# import contract in pyproject.toml keeps them from importing the domain
BASE = {"climb.schema", "climb.ids", "climb.storage", "climb.standing"}


def modules() -> dict[str, Path]:
    found = {}
    for path in sorted((SRC / "climb").rglob("*.py")):
        parts = list(path.relative_to(SRC).with_suffix("").parts)
        if parts[-1] == "__init__":
            parts.pop()
        found[".".join(parts)] = path
    return found


def imports(path: Path, known: dict[str, Path]) -> set[str]:
    found: set[str] = set()
    for n in ast.walk(ast.parse(path.read_text())):
        names = []
        if isinstance(n, ast.Import):
            names = [a.name for a in n.names]
        elif isinstance(n, ast.ImportFrom) and n.module:
            names = [
                f"{n.module}.{a.name}" if f"{n.module}.{a.name}" in known else n.module
                for a in n.names
            ]
        for name in names:
            parts = name.split(".")
            # an import runs every package above the module it names
            found |= {".".join(parts[:i]) for i in range(2, len(parts) + 1)}
    return found & known.keys()


def reached(graph: dict[str, set[str]], entries: list[str]) -> set[str]:
    seen: set[str] = set()
    # an entry is run, so the packages above it run only where imported
    todo = list(entries)
    while todo:
        m = todo.pop()
        if m not in seen:
            seen.add(m)
            todo += graph[m]
    return seen


def package(module: str) -> str:
    return ".".join(module.split(".")[:2])


def reduced(edges: dict[str, set[str]]) -> dict[str, set[str]]:
    # an import a chain of drawn imports already implies is left out
    def further(source: str, skip: str) -> set[str]:
        seen: set[str] = set()
        todo = [n for n in edges.get(source, ()) if n != skip]
        while todo:
            n = todo.pop()
            if n not in seen:
                seen.add(n)
                todo += edges.get(n, ())
        return seen

    return {s: {t for t in ts if t not in further(s, t)} for s, ts in edges.items()}


def joined(names: list[str]) -> str:
    return names[0] if len(names) == 1 else f"{', '.join(names[:-1])} and {names[-1]}"


def key(name: str) -> str:
    return name.replace(".", "_")


def graph(model: dict) -> tuple[list[str], list[str]]:
    known = modules()
    deps = {m: imports(p, known) for m, p in known.items()}
    holders = [e for e in model["element"] if "code" in e]
    found = [
        f"`{e['id']}` names `{m}`, which is not a module of src/climb"
        for e in holders
        for m in e["code"]
        if m not in known
    ]
    if found:
        return [], found
    reach = {e["id"]: {package(m) for m in reached(deps, e["code"])} for e in holders}
    reach = {i: r - {"climb"} for i, r in reach.items()}
    for e in holders:
        declared = set(e.get("runs", []))
        found += [
            f"`{p}` runs in `{e['id']}`, whose `runs` omits it"
            for p in sorted(reach[e["id"]] - declared)
        ]
        found += [
            f"`{p}` is in `{e['id']}`'s `runs`, which its `code` does not reach"
            for p in sorted(declared - reach[e["id"]])
        ]
    packages = sorted({package(m) for m in known} - {"climb"})
    groups: dict[tuple[str, ...], list[str]] = {}
    for p in packages:
        groups.setdefault(tuple(e["id"] for e in holders if p in reach[e["id"]]), []).append(p)
    found += [f"`{p}` is reached by no container's `code`" for p in groups.pop((), [])]
    names = {e["id"]: e["name"] for e in holders}
    edges: dict[str, set[str]] = {}
    for m, ds in deps.items():
        edges.setdefault(package(m), set()).update(
            package(d) for d in ds if package(d) not in {package(m), *BASE}
        )
    lines = ["flowchart LR"]
    for n, (owners, members) in enumerate(sorted(groups.items(), key=lambda g: (len(g[0]), g[0]))):
        lines.append(f'    subgraph g{n}["{joined([names[o] for o in owners])}"]')
        lines += [f'        {key(p)}["{p.removeprefix("climb.")}"]' for p in members]
        lines.append("    end")
    for s, ts in sorted(reduced(edges).items()):
        lines += [f"    {key(s)} --> {key(t)}" for t in sorted(ts) if s != "climb" and t != "climb"]
    return lines, found


def contracts(model: dict) -> list[str]:
    packages = sorted({package(m) for m in modules()} - {"climb"})
    lines = []
    for e in model["element"]:
        if "code" not in e:
            continue
        own = sorted({package(m) for m in e["code"]})
        # a module's own package runs it as a script or as an entry, as the
        # local runner forks `climb.runner.child`
        entries = sorted(m for m in e["code"] if not any(m.startswith(f"{o}.") for o in e["code"]))
        sources = textwrap.wrap(
            " ".join(f'"{p}",' for p in packages if p not in own), 84, break_on_hyphens=False
        )
        forbidden = ", ".join(f'"{m}"' for m in entries)
        lines += [
            "",
            "[[tool.importlinter.contracts]]",
            f'name = "nothing outside {joined(own)} imports the {e["name"]}\'s code"',
            'type = "forbidden"',
            "source_modules = [",
            *(f"    {line}" for line in sources),
            "]",
            f"forbidden_modules = [{forbidden}]",
            "allow_indirect_imports = true",
        ]
    return lines


def rendered_rules(text: str, lines: list[str]) -> str:
    head, rest = text.split(RULES_BEGIN, 1)
    return head + "\n".join([RULES_BEGIN, *lines, RULES_END]) + rest.split(RULES_END, 1)[1]


def rendered(text: str, lines: list[str]) -> str:
    head, rest = text.split(BEGIN, 1)
    block = [BEGIN, "", "```mermaid", *lines, "```", "", END]
    return head + "\n".join(block) + rest.split(END, 1)[1]


def main(command: str) -> int:
    model = tomllib.loads(MODEL.read_text())
    lines, found = graph(model)
    if not found:
        targets = [
            (PAGE, "`modules.md`", lambda t: rendered(t, lines)),
            (
                PYPROJECT,
                "the generated contracts in `pyproject.toml`",
                lambda t: rendered_rules(t, contracts(model)),
            ),
        ]
        for path, name, render in targets:
            text = path.read_text()
            if command == "write":
                path.write_text(render(text))
            elif render(text) != text:
                found.append(f"{name} is stale: run `just module-graph`")
    for line in found:
        sys.stderr.write(f"module graph: {line}\n")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "check"))
