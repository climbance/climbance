"""Generate the clients' TypeScript import graph in
`docs/architecture/client-modules.md`, a box per workspace, and check it.

    python3 tools/client_graph.py write   # rewrite the graph
    python3 tools/client_graph.py check   # fail on a stale graph
"""

import re
import sys
import tomllib
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs" / "architecture"
MODEL = DOCS / "model.toml"
PAGE = DOCS / "client-modules.md"
BEGIN = "<!-- the {} graph, generated by `just module-graph`, never edited -->"
END = "<!-- end of the generated {} graph -->"
# (key, model.toml id, source root, package name)
WORKSPACES = [
    ("web", "web-app", "web/src", None),
    ("native", "native-app", "native/src", None),
    ("core", "core-package", "packages/core/src", "@climb/core"),
    ("editor", "shared-editor", "packages/editor/src", "@climb/editor"),
]
# the editor page's source, bundled into native/src/editor by `just editor-page`
EXTRA = {"native/editor": ("native", "editor page")}

IMPORT = re.compile(
    r"^\s*(?:import|export)\b([^;='\"]*?)\bfrom\s*['\"]([^'\"]+)['\"]"
    r"|^\s*import\s*['\"]([^'\"]+)['\"]",
    re.M,
)
DEFINED = re.compile(
    r"^export\s+(?:declare\s+)?(?:default\s+)?(?:async\s+)?(?:abstract\s+)?"
    r"(?:const|let|var|function\*?|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)",
    re.M,
)
LOCAL_EXPORT = re.compile(r"^export\s+(?:type\s+)?\{([^}]*)\}\s*;?\s*$", re.M)
SUFFIXES = (".ts", ".tsx", ".d.ts")
BARRELS = {ROOT / r / "index.ts" for _, _, r, p in WORKSPACES if p}


def sources() -> dict[Path, tuple[str, str]]:
    """Each source file, with its workspace and its node."""
    found: dict[Path, tuple[str, str]] = {}
    roots = [(ROOT / r, k, None) for k, _, r, _ in WORKSPACES]
    roots += [(ROOT / r, k, n) for r, (k, n) in EXTRA.items()]
    for root, ws, node in roots:
        for path in sorted(root.rglob("*")):
            if path.suffix not in SUFFIXES or ".test." in path.name or path in BARRELS:
                continue
            # an ambient declaration file is imported by nothing
            if path.name.endswith(".d.ts") and not re.search(r"^export\b", path.read_text(), re.M):
                continue
            top = path.relative_to(root).parts[0]
            found[path] = (ws, node or re.sub(r"(\.d)?\.tsx?$", "", top))
    return found


def resolve(base: Path) -> Path | None:
    for candidate in (base, *(base.with_name(base.name + s) for s in SUFFIXES)):
        if candidate.is_file():
            return candidate
    return next((base / f"index{s}" for s in SUFFIXES if (base / f"index{s}").is_file()), None)


def names(clause: str) -> list[str] | None:
    """The names an import clause takes, or None for a namespace import."""
    if "*" in clause:
        return None
    inner = clause[clause.find("{") + 1 : clause.rfind("}")] if "{" in clause else ""
    taken: list[str] = []
    for part in inner.split(","):
        words = part.split()
        if words and words[0] == "type":
            words = words[1:]
        if words:
            taken.append(words[0])
    return taken


def definitions(root: Path) -> dict[str, Path]:
    found: dict[str, Path] = {}
    for path in sorted(root.rglob("*")):
        if path.suffix not in SUFFIXES or ".test." in path.name or path.stem == "index":
            continue
        text = path.read_text()
        for name in DEFINED.findall(text):
            found.setdefault(name, path)
        for clause in LOCAL_EXPORT.findall(text):
            for part in clause.split(","):
                words = part.split()
                if words:
                    found.setdefault(words[-1], path)
    return found


def target(path: Path, ws: str, spec: str) -> Path | None:
    if spec.startswith("."):
        return resolve(path.parent / spec)
    if spec.startswith("@/") and ws in ("web", "native"):
        return resolve(ROOT / next(r for k, _, r, _ in WORKSPACES if k == ws) / spec[2:])
    for _, _, root, package in WORKSPACES:
        if package and (spec == package or spec.startswith(f"{package}/")):
            return resolve(ROOT / root / spec.removeprefix(package).lstrip("/"))
    return None


def edges(files: dict[Path, tuple[str, str]]) -> tuple[dict[str, set[str]], list[str]]:
    defined = {b: definitions(b.parent) for b in BARRELS}
    found: dict[str, set[str]] = {}
    problems: list[str] = []
    for path, (ws, node) in files.items():
        source = f"{ws}.{node}"
        found.setdefault(source, set())
        for clause, spec, bare in IMPORT.findall(path.read_text()):
            spec = spec or bare
            if not spec.startswith((".", "@/", "@climb/")):
                continue
            to = target(path, ws, spec)
            where = f"`{spec}` in `{path.relative_to(ROOT)}`"
            targets = [to]
            # the barrel re-exports every file, so an import through it is
            # drawn to the file defining each name it takes
            if to in BARRELS:
                taken = names(clause)
                if not taken:
                    problems.append(f"{where} takes no named import from the barrel")
                targets = [defined[to].get(n) for n in taken or []]
                problems += [
                    f"{where}: `{n}` is defined in no file"
                    for n in taken or []
                    if n not in defined[to]
                ]
            for t in targets:
                if t is None:
                    problems.append(f"{where} resolves to no file")
                elif t in files and files[t] != (ws, node):
                    found[source].add(".".join(files[t]))
    return found, sorted(set(problems))


def reduced(graph: dict[str, set[str]]) -> dict[str, set[str]]:
    # an import that another chain of drawn imports implies is left out, one
    # at a time: the clients' imports have cycles, and in a cycle two edges
    # can each imply the other
    kept = {s: set(ts) for s, ts in graph.items()}

    def reaches(source: str, target: str) -> bool:
        seen, todo = {source}, [n for n in kept[source] if n != target]
        while todo:
            n = todo.pop()
            if n == target:
                return True
            if n not in seen:
                seen.add(n)
                todo += kept.get(n, ())
        return False

    for s in sorted(kept):
        for t in sorted(kept[s]):
            if reaches(s, t):
                kept[s].discard(t)
    return kept


def key(node: str) -> str:
    return re.sub(r"\W", "_", node)


def joined(names: list[str]) -> str:
    return names[0] if len(names) == 1 else f"{', '.join(names[:-1])} and {names[-1]}"


def drawn(deps: dict[str, set[str]], nodes: list[str]) -> list[str]:
    kept = {n: deps.get(n, set()) & set(nodes) for n in nodes}
    return [
        f"    {key(s)} --> {key(t)}" for s, ts in sorted(reduced(kept).items()) for t in sorted(ts)
    ]


def graphs(model: dict[str, Any]) -> tuple[dict[str, list[str]], list[str]]:
    files = sources()
    deps, problems = edges(files)
    names = {e["id"]: e["name"] for e in model["element"]}
    labels = {ws: names[label] for ws, label, _, _ in WORKSPACES}
    shared = [ws for ws, _, _, package in WORKSPACES if package]
    clients = [ws for ws in labels if ws not in shared]

    def node(n: str) -> str:
        return n.split(".")[0] if n.split(".")[0] in shared else n

    # the clients' graph draws each shared package as one node
    collapsed: dict[str, set[str]] = {}
    for s, ts in deps.items():
        collapsed.setdefault(node(s), set()).update(node(t) for t in ts if node(t) != node(s))
    outer = ["flowchart LR"]
    for ws in clients:
        outer.append(f'    subgraph {ws}["{labels[ws]}"]')
        outer += [
            f'        {key(n)}["{n.split(".", 1)[1]}"]'
            for n in sorted(collapsed)
            if n.startswith(f"{ws}.")
        ]
        outer.append("    end")
    outer += [f'    {ws}["{labels[ws]}"]' for ws in shared]
    outer += drawn(collapsed, sorted(collapsed))

    # the shared graph boxes each file by the clients whose code reaches it
    def reach(start: str) -> set[str]:
        seen: set[str] = set()
        todo = list(deps[start])
        while todo:
            n = todo.pop()
            if n not in seen:
                seen.add(n)
                todo += deps.get(n, ())
        return seen

    reached = {
        ws: set[str]().union(*(reach(n) for n in deps if n.startswith(f"{ws}."))) for ws in clients
    }
    groups: dict[tuple[str, str], list[str]] = {}
    for n in sorted(n for n in deps if node(n) != n):
        users = joined([labels[ws] for ws in clients if n in reached[ws]] or ["no client"])
        groups.setdefault((n.split(".")[0], users), []).append(n)
    inner = ["flowchart LR"]
    for i, ((ws, users), members) in enumerate(sorted(groups.items())):
        inner.append(f'    subgraph g{i}["{labels[ws]}: {users}"]')
        inner += [f'        {key(n)}["{n.split(".", 1)[1]}"]' for n in members]
        inner.append("    end")
    inner += drawn(deps, [n for ms in groups.values() for n in ms])
    return {"clients": outer, "shared": inner}, problems


def rendered(text: str, name: str, lines: list[str]) -> str:
    begin, end = BEGIN.format(name), END.format(name)
    head, rest = text.split(begin, 1)
    block = [begin, "", "```mermaid", *lines, "```", "", end]
    return head + "\n".join(block) + rest.split(end, 1)[1]


def main(command: str) -> int:
    drawings, found = graphs(tomllib.loads(MODEL.read_text()))
    if not found:
        text = PAGE.read_text()
        new = text
        for name, lines in drawings.items():
            new = rendered(new, name, lines)
        if command == "write":
            PAGE.write_text(new)
        elif new != text:
            found.append("`client-modules.md` is stale: run `just module-graph`")
    for line in found:
        sys.stderr.write(f"client graph: {line}\n")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "check"))
