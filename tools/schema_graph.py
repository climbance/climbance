"""Generate the database schema graph in `docs/architecture/database/schema.md`
from the declared tables: each table in the box of the component whose
`tables` in `docs/architecture/model.toml` names it, and its foreign keys.

    uv run python tools/schema_graph.py write   # rewrite the graph
    uv run python tools/schema_graph.py check   # fail on a stale graph or owner
"""

import importlib
import sys
import tomllib
from pathlib import Path

from sqlalchemy import Table

from climb.storage import metadata

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "climb"
DOCS = ROOT / "docs" / "architecture"
MODEL = DOCS / "model.toml"
PAGE = DOCS / "database" / "schema.md"
BEGIN = "<!-- generated by `just module-graph`, never edited -->"
END = "<!-- end of the generated graph -->"
# nearly every table references these, so the graph draws no arrow into them
# and the list below the graph names each reference
UNDRAWN = {"users", "calls"}


def tables() -> dict[str, Table]:
    for path in sorted(SOURCE.rglob("table.py")):
        importlib.import_module(
            ".".join(("climb", *path.relative_to(SOURCE).with_suffix("").parts))
        )
    return dict(metadata.tables)


def owners(model: dict, known: dict[str, Table]) -> tuple[dict[str, str], list[str]]:
    owner: dict[str, str] = {}
    found = []
    for e in model["element"]:
        for t in e.get("tables", []):
            if t not in known:
                found.append(f"`{e['id']}` names `{t}`, which no table declares")
            elif t in owner:
                found.append(f"`{t}` is named by both `{owner[t]}` and `{e['id']}`")
            else:
                owner[t] = e["id"]
    found += [f"`{t}` is named by no element's `tables`" for t in sorted(known.keys() - owner)]
    return owner, found


def references(table: Table) -> list[tuple[str, str]]:
    # a composite key is one reference, its columns named together
    found = []
    for k in table.foreign_key_constraints:
        columns = ", ".join(f"`{c}`" for c in k.column_keys)
        found.append((f"({columns})" if len(k.column_keys) > 1 else columns, k.referred_table.name))
    return sorted(found)


def graph(model: dict, known: dict[str, Table], owner: dict[str, str]) -> list[str]:
    elements = {e["id"]: e for e in model["element"]}
    lines = ["flowchart LR"]
    containers: dict[str, list[str]] = {}
    for o in sorted(set(owner.values())):
        containers.setdefault(elements[o].get("container", o), []).append(o)
    for c, members in sorted(containers.items()):
        lines.append(f'    subgraph {c.replace("-", "_")}["{elements[c]["name"]}"]')
        for o in members:
            lines.append(f'        subgraph {o.replace("-", "_")}_tables["{elements[o]["name"]}"]')
            lines += [f"            {t}" for t in sorted(owner) if owner[t] == o]
            lines.append("        end")
        lines.append("    end")
    for name, table in sorted(known.items()):
        targets = sorted({t for _, t in references(table)} - UNDRAWN - {name})
        lines += [f"    {name} --> {t}" for t in targets]
    return lines


def listing(model: dict, known: dict[str, Table], owner: dict[str, str]) -> list[str]:
    names = {e["id"]: e["name"] for e in model["element"]}
    rows = ["| Table | Owner | Foreign keys |", "|---|---|---|"]
    for name, table in sorted(known.items()):
        keys = ", ".join(f"{c} → `{t}`" for c, t in references(table))
        rows.append(f"| `{name}` | {names[owner[name]]} | {keys} |")
    return rows


def rendered(text: str, lines: list[str], rows: list[str]) -> str:
    head, rest = text.split(BEGIN, 1)
    block = [BEGIN, "", "```mermaid", *lines, "```", "", *rows, "", END]
    return head + "\n".join(block) + rest.split(END, 1)[1]


def main(command: str) -> int:
    model = tomllib.loads(MODEL.read_text())
    known = tables()
    owner, found = owners(model, known)
    if not found:
        text = PAGE.read_text()
        new = rendered(text, graph(model, known, owner), listing(model, known, owner))
        if command == "write":
            PAGE.write_text(new)
        elif new != text:
            found.append("`database/schema.md` is stale: run `just module-graph`")
    for line in found:
        sys.stderr.write(f"schema graph: {line}\n")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "check"))
